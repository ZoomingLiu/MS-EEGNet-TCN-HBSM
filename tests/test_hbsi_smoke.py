import pickle

import numpy as np
import pytest

from hbsm_loso.hbsi_main_loso import main, run_loso_pipeline
from hbsm_loso.hbsi_visualization import generate_diagnostic_figures


def make_subject(root, first_level=0.1):
    subject = root / "subject_01"
    subject.mkdir(parents=True)
    length = 40
    risk = np.r_[np.full(length, first_level), np.linspace(0.1, 0.95, length)]
    arrays = {
        "tcn_risk": risk.astype(np.float32),
        "tcn_embedding_128": np.zeros((2 * length, 128), dtype=np.float32),
        "tcn_logits": np.zeros((2 * length, 2), dtype=np.float32),
        "labels": np.r_[np.zeros(length), np.ones(length)].astype(np.int64),
        "sequence_records": np.array(["record_a"] * length + ["record_b"] * length),
        "sequence_end_seconds": np.tile(np.arange(length) * 2.5 + 5, 2),
    }
    for name, values in arrays.items():
        np.save(subject / f"{name}.npy", values)
    return subject


def test_cli_pickle_visualization_and_record_isolation(tmp_path):
    data = tmp_path / "data"
    make_subject(data)
    output = tmp_path / "outputs" / "run_001" / "results.pkl"
    main(["--data-dir", str(data), "--output", str(output)])
    with output.open("rb") as handle:
        result = pickle.load(handle)[0]  # Generated by this test, not an external pickle.
    assert result.hsmm_state_probabilities.shape == (80, 3)
    np.testing.assert_allclose(result.hsmm_state_probabilities.sum(axis=1), 1, atol=1e-6)
    assert np.isfinite(result.bocpd_change_probability).all()
    figures = generate_diagnostic_figures(output, data, tmp_path / "figures")
    assert len(figures) == 1 and "<svg" in figures[0].read_text(encoding="utf-8")
    with pytest.raises(SystemExit) as exc:
        main(["--data-dir", str(data), "--output", str(output)])
    assert exc.value.code == 2

    other_data = tmp_path / "other_data"
    make_subject(other_data, first_level=0.99)
    other_output = tmp_path / "other.pkl"
    run_loso_pipeline(other_data, other_output)
    with other_output.open("rb") as handle:
        other = pickle.load(handle)[0]
    np.testing.assert_array_equal(result.hsmm_state_probabilities[40:], other.hsmm_state_probabilities[40:])
    np.testing.assert_array_equal(result.bocpd_change_probability[40:], other.bocpd_change_probability[40:])
